#pragma once

#include "IntegratedBC.h"
#include "MooseAST.h"
#include "ExpressionEvaluator.h"

/**
 * Boundary condition kernel for natural boundary conditions derived from energy functionals
 *
 * This kernel evaluates boundary integrals that arise from integration by parts when deriving
 * weak forms from variational principles. The boundary term has the form:
 *
 *   ∫_∂Ω sign * (coefficient · n) * v ds
 *
 * where:
 *   - coefficient is the variational derivative coefficient (e.g., k*grad(u))
 *   - n is the outward unit normal
 *   - v is the test function
 *   - sign is ±1 from integration by parts (alternates with derivative order)
 *
 * This kernel is automatically generated by AutomaticWeakFormAction when boundary terms
 * are extracted from energy functionals.
 */
class VariationalBC : public IntegratedBC
{
public:
  static InputParameters validParams();

  VariationalBC(const InputParameters & parameters);

protected:
  virtual Real computeQpResidual() override;
  virtual Real computeQpJacobian() override;
  virtual Real computeQpOffDiagJacobian(unsigned int jvar) override;

private:
  /// The boundary term expression (includes coefficient, normal contraction, and sign)
  /// Expression should be of form: sign * (coefficient · normal)
  /// The test function multiplication is handled by computeQpResidual
  moose::automatic_weak_form::NodePtr _boundary_expr;

  /// Expression evaluator for runtime evaluation
  std::unique_ptr<moose::automatic_weak_form::ExpressionEvaluator> _evaluator;

  /// Coupled variable names and IDs
  std::vector<std::string> _coupled_var_names;
  std::vector<unsigned int> _coupled_var_ids;
  std::vector<const VariableValue *> _coupled_vals;
  std::vector<const VariableGradient *> _coupled_grads;

  /// Whether to use automatic differentiation for Jacobian
  bool _use_ad;

  /// Optional: Jacobian expression (if not using AD)
  moose::automatic_weak_form::NodePtr _jacobian_expr;

  /// Optional: Off-diagonal Jacobian expressions
  std::map<unsigned int, moose::automatic_weak_form::NodePtr> _off_diag_jacobian_exprs;

  /// Set up the evaluation context with current QP values
  void setupEvaluationContext();
};
